export function shot(t) {
  const i = t < 7.5 ? 0 : t < 14.5 ? 1 : t < 19.8 ? 2 : t < 24.2 ? 3 : 4;
  const [a, b, p0, p1, c0, c1, f0, f1] = shots[i],
    u = (t - a) / (b - a),
    k = u * u * (3 - 2 * u);
  return {
    i,
    eye: V(...p0).lerp(V(...p1), k),
    target: V(...c0).lerp(V(...c1), k),
    fov: f0 + (f1 - f0) * k,
  };
}
export function prismAngle(t) {
  return -17.2 - 7.2 * Math.cos(t * 0.20944 + 0.21) + 4.1 * Math.sin(t * 0.41);
}
